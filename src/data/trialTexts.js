/**
 * 取某界某关口的文案；未登记界 / 越界 / 空段一律返回 ''（调用方回落 `TRIAL_NODES[i].desc`）。
 * @param {string} worldId 当前世界 id（state.world.worldId）
 * @param {number} index   TRIAL_NODES 的 index（0~7）
 */
export function trialTextOf (worldId, index) {
  const list = TRIAL_WORLD_TEXTS[worldId]
  if (!Array.isArray(list)) return ''
  const t = list[index]
  return typeof t === 'string' ? t : ''
}

